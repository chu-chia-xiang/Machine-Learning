def train_epoch(model, loader, optimizer, criterion, device, log_interval=10000):
    model.train()
    running_loss = 0.0
    total_seen = 0

    for batch_idx, (data, target) in enumerate(loader):
        data, target = data.to(device), target.to(device)
        out = model(data)
        loss = criterion(out, target)

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        # 統計
        batch_size = data.size(0)
        running_loss += loss.item() * batch_size
        total_seen += batch_size

        # 每 log_interval 張圖顯示一次
        if total_seen % log_interval == 0 or total_seen == len(loader.dataset):
            avg_loss = running_loss / total_seen
            print(f"[{total_seen}/{len(loader.dataset)} ({100. * total_seen / len(loader.dataset):.0f}%)] "
                  f"Loss: {avg_loss:.4f}")
def evaluate(model, loader, criterion, device):
    model.eval()
    total_loss = 0.0
    correct    = 0

    with torch.no_grad():
        for data, target in loader:
            data, target = data.to(device), target.to(device)
            out = model(data)
            total_loss += criterion(out, target).item() * data.size(0)
            preds = out.argmax(dim=1)
            correct += (preds == target).sum().item()

    avg_loss = total_loss / len(loader.dataset)
    accuracy = correct / len(loader.dataset)

    # 印出平均測試損失與準確率
    print(f"\nAverage test loss: {avg_loss:.4f}  Accuracy: {correct}/{len(loader.dataset)} ({accuracy*100:.2f}%)\n")
    return avg_loss, accuracy

