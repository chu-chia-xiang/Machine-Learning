import torch.nn as nn
from einops import rearrange, repeat

def pair(t): return t if isinstance(t, tuple) else (t,t)

class PreNorm(nn.Module):
    def __init__(self, dim, fn):
        super().__init__()
        self.norm = nn.LayerNorm(dim)
        self.fn   = fn
    def forward(self, x, **kw):
        return self.fn(self.norm(x), **kw)

class FeedForward(nn.Module):
    def __init__(self, dim, hidden, dropout=0.):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(dim, hidden),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(hidden, dim),
            nn.Dropout(dropout)
        )
    def forward(self, x): return self.net(x)

class Attention(nn.Module):
    def __init__(self, dim, heads=4, dim_head=64, dropout=0.):
        super().__init__()
        inner = dim_head * heads
        self.heads = heads
        self.scale = dim_head ** -0.5
        self.to_qkv = nn.Linear(dim, inner*3, bias=False)
        self.to_out = nn.Sequential(
            nn.Linear(inner, dim),
            nn.Dropout(dropout)
        )
    def forward(self, x):
        b,n,_ = x.shape
        qkv = self.to_qkv(x).chunk(3, dim=-1)
        q,k,v = map(lambda t: rearrange(t, 'b n (h d)-> b h n d', h=self.heads), qkv)
        attn = (q @ k.transpose(-2,-1)) * self.scale
        attn = attn.softmax(dim=-1)
        out  = attn @ v
        out  = rearrange(out, 'b h n d-> b n (h d)')
        return self.to_out(out)

class Transformer(nn.Module):
    def __init__(self, dim, depth, heads, dim_head, mlp_dim, dropout=0.):
        super().__init__()
        self.layers = nn.ModuleList()
        for _ in range(depth):
            self.layers.append(nn.ModuleList([
                PreNorm(dim, Attention(dim, heads, dim_head, dropout)),
                PreNorm(dim, FeedForward(dim, mlp_dim, dropout))
            ]))
    def forward(self, x):
        for attn, ff in self.layers:
            x = x + attn(x)
            x = x + ff(x)
        return x

class ViT(nn.Module):
    def __init__(self, image_size, patch_size, num_classes,
                 dim, depth, heads, mlp_dim,
                 channels=1, dim_head=64, dropout=0., emb_dropout=0.,
                 pool='cls'):
        super().__init__()
        h,w = pair(image_size); ph,pw = pair(patch_size)
        assert h%ph==0 and w%pw==0, "Patch must divide image"
        num_patches = (h//ph)*(w//pw)

        self.to_patch = nn.Conv2d(channels, dim, kernel_size=patch_size, stride=patch_size)
        self.cls_token     = nn.Parameter(torch.randn(1,1,dim))
        self.pos_embedding = nn.Parameter(torch.randn(1, num_patches+1, dim))
        self.dropout       = nn.Dropout(emb_dropout)

        self.transformer = Transformer(dim, depth, heads, dim_head, mlp_dim, dropout)
        self.pool        = pool
        self.mlp_head    = nn.Sequential(
            nn.LayerNorm(dim),
            nn.Linear(dim, num_classes)
        )

    def forward(self, img):
        x = self.to_patch(img)
        x = rearrange(x, 'b c h w-> b (h w) c')
        b,n,_ = x.shape
        cls = repeat(self.cls_token, '1 1 d-> b 1 d', b=b)
        x = torch.cat([cls, x], dim=1)
        x = x + self.pos_embedding[:,:n+1]
        x = self.dropout(x)
        x = self.transformer(x)
        x = x[:,0] if self.pool=='cls' else x.mean(dim=1)
        return self.mlp_head(x)

