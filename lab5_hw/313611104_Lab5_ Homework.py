    # === OPTION 1: Early Stopping ===
    print("Training with Early Stopping:")
    model_early = MLP(input_dim, hidden_dim, output_dim, weight_decay=0.0)
    t1, v1, a1, a2 = train(model_early, X_train, y_train_oh, X_val, y_val_oh,
                           lr=0.1, epochs=100, use_early_stopping=True, patience=5)
    plot_curves(t1, v1, a1, a2, title="Early Stopping")

    # === OPTION 2: Weight Decay (L2 Regularization) ===
    print("Training with Weight Decay (L2 Regularization) for different λ values:")
    lambda_values = [0.0, 0.001, 0.01]  # 可嘗試的不同正則化強度
    for lam in lambda_values:
        print(f"\nTraining with weight_decay = {lam}")
        model_wd = MLP(input_dim, hidden_dim, output_dim, weight_decay=lam)
        t_loss, v_loss, t_acc, v_acc = train(model_wd, X_train, y_train_oh, X_val, y_val_oh,
                                             lr=0.1, epochs=100, use_early_stopping=False)
        plot_curves(t_loss, v_loss, t_acc, v_acc, title=f"Weight Decay (λ = {lam})")