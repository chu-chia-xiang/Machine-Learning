def compute_confusion_matrix(y_true, y_pred, num_classes=10):
    cm = np.zeros((num_classes, num_classes), dtype=int)
    for t, p in zip(y_true, y_pred):
        cm[t, p] += 1
    return cm

def compute_metrics_verbose(cm):
    num_classes = cm.shape[0]
    total = np.sum(cm)
    total_correct = 0

    for i in range(num_classes):
        tp = cm[i, i]
        fp = np.sum(cm[:, i]) - tp
        fn = np.sum(cm[i, :]) - tp
        tn = total - (tp + fp + fn)

        precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
        recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
        f1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else 0.0

        total_correct += tp

        print(f"Class {i}:")
        print(f"TP: {tp}, FP: {fp}, FN: {fn}, TN: {tn}")
        print(f"Precision: {precision:.4f}")
        print(f"Recall: {recall:.4f}")
        print(f"F1 Score: {f1:.4f}\n")

    overall_accuracy = total_correct / total
    print(f"Overall Accuracy: {overall_accuracy:.4f}")

def plot_confusion_matrix(cm):
    plt.figure(figsize=(6,5))
    sns.heatmap(cm, annot=True, fmt="d", cmap="Blues")
    plt.xlabel("Predicted")
    plt.ylabel("True")
    plt.title("Confusion Matrix")
    plt.show()

def compute_roc_for_class(y_true_binary, y_score):
    thresholds = np.linspace(0,1,50)
    tpr_vals = []
    fpr_vals = []
    P = np.sum(y_true_binary==1)
    N = np.sum(y_true_binary==0)

    for thr in thresholds:
        y_pred_positive = (y_score >= thr).astype(int)
        tp = np.sum((y_pred_positive==1) & (y_true_binary==1))
        fp = np.sum((y_pred_positive==1) & (y_true_binary==0))
        tpr = tp / P if P>0 else 0
        fpr = fp / N if N>0 else 0
        tpr_vals.append(tpr)
        fpr_vals.append(fpr)
    return np.array(fpr_vals), np.array(tpr_vals)

def plot_roc(y_true_oh, y_pred_proba):
    plt.figure(figsize=(7,6))
    num_classes = y_true_oh.shape[1]
    for c in range(num_classes):
        fpr, tpr = compute_roc_for_class(y_true_oh[:, c], y_pred_proba[:, c])
        plt.plot(fpr, tpr, label=f"Class {c}")
    plt.plot([0,1],[0,1], '--', color='gray')
    plt.xlabel("False Positive Rate")
    plt.ylabel("True Positive Rate")
    plt.title("ROC Curve (One-vs-Rest)")
    plt.legend()
    plt.show()

