def relu(x):  # Eq. 6.17
    return np.maximum(0, x)

def tanh(x):  # Eq. 6.14
    return np.tanh(x)

def softplus(x):  # Eq. 6.16
    return np.log1p(np.exp(x))

def leaky_relu(x, alpha=0.1):  # Eq. 6.18
    return np.maximum(0, x) + alpha * np.minimum(0, x)

def one_hot(y, num_classes=10):
    oh = np.zeros((len(y), num_classes))
    for i, val in enumerate(y):
        oh[i, val] = 1.0
    return oh

def cross_entropy(y_pred, y_true):
    """
    y_pred: (N, K) softmax outputs
    y_true: (N, K) one-hot labels
    """
    eps = 1e-12  # 防止 log(0)
    return -np.sum(y_true * np.log(y_pred + eps)) / y_pred.shape[0]

def softmax(a):
    """
    a: (N, K) raw scores
    return: (N, K) softmax probabilities
    """
    a_stable = a - np.max(a, axis=1, keepdims=True)
    exp_a = np.exp(a_stable)
    return exp_a / np.sum(exp_a, axis=1, keepdims=True)

def forward_pass(X, weights, activations):

    out = X
    for W, act in zip(weights, activations):
        z = out @ W
        out = act(z)
    return out

